/* JIMMY RACING - shaders.js : all GLSL ES 3.00 sources */
(function () {
  var G = (typeof globalThis !== 'undefined' ? globalThis : window);
  G.JR = G.JR || {};
  var JR = G.JR;
  var S = {};

  /* ------------------------------------------------------------ shared chunks */
  var NOISE = [
    'float hash12(vec2 p){ vec3 p3=fract(vec3(p.xyx)*.1031); p3+=dot(p3,p3.yzx+33.33); return fract((p3.x+p3.y)*p3.z); }',
    'float hash13(vec3 p3){ p3=fract(p3*.1031); p3+=dot(p3,p3.zyx+31.32); return fract((p3.x+p3.y)*p3.z); }',
    'float vnoise(vec2 p){ vec2 i=floor(p), f=fract(p); f=f*f*(3.-2.*f);',
    '  return mix(mix(hash12(i),hash12(i+vec2(1,0)),f.x), mix(hash12(i+vec2(0,1)),hash12(i+vec2(1,1)),f.x), f.y); }',
    'float fbm(vec2 p){ float s=0., a=.5; for(int i=0;i<5;i++){ s+=a*vnoise(p); p=p*2.03+vec2(17.1,9.7); a*=.5; } return s; }',
    'float fbm3(vec2 p){ float s=0., a=.5; for(int i=0;i<3;i++){ s+=a*vnoise(p); p=p*2.03+vec2(17.1,9.7); a*=.5; } return s; }'
  ].join('\n');

  var SKY_COMMON = [
    'uniform vec3 uSunDir; uniform vec3 uSunCol; uniform vec3 uSkyZen; uniform vec3 uSkyHor; uniform vec3 uGround;',
    'uniform float uCloud; uniform float uNight; uniform float uTime; uniform vec3 uMoonDir;',
    'vec3 skyBase(vec3 d, float sunDisk){',
    '  float h = clamp(d.y, 0., 1.);',
    '  vec3 col = mix(uSkyHor, uSkyZen, pow(h, .42));',
    '  if (d.y < 0.) col = mix(uSkyHor * .85, uGround, smoothstep(0., -.18, d.y));',
    '  float sd = max(dot(d, uSunDir), 0.);',
    '  col += uSunCol * (pow(sd, 6.) * .06 + pow(sd, 64.) * .12 + pow(sd, 700.) * .9 + sunDisk * smoothstep(.99985, .99996, sd) * 60.);',
    '  return col;',
    '}'
  ].join('\n');

  /* ------------------------------------------------------------ lit vertex */
  S.litVS = [
    'precision highp float;',
    'in vec3 aPos; in vec3 aNrm; in vec2 aUV; in vec4 aCol; in vec4 aM0; in vec4 aM1; in vec4 aM2; in vec4 aTint;',
    'uniform mat4 uViewProj; uniform vec4 uClip;',
    '#ifdef CAR',
    'uniform vec4 uDamage; uniform vec2 uCarHalf;',
    'float h13(vec3 p3){ p3=fract(p3*.1031); p3+=dot(p3,p3.zyx+31.32); return fract((p3.x+p3.y)*p3.z); }',
    '#endif',
    '#ifdef SWAY',
    'uniform float uTime; uniform vec2 uWind;',
    '#endif',
    'out vec3 vWorld; out vec3 vN; out vec2 vUV; out vec4 vCol; out vec4 vTint;',
    '#ifdef CAR',
    'out vec3 vLoc;',
    '#endif',
    'void main(){',
    '  vec3 lp = aPos;',
    '#ifdef CAR',
    '  vLoc = aPos;',
    '#endif',
    '#ifdef CAR',
    '  float fx = clamp(lp.z / uCarHalf.x, -1., 1.), sx = clamp(lp.x / uCarHalf.y, -1., 1.);',
    '  float nz = h13(floor(lp * 6.)) * .6 + h13(floor(lp * 14.)) * .4;',
    '  float front = uDamage.x * smoothstep(.30, 1., fx), rear = uDamage.y * smoothstep(.30, 1., -fx);',
    '  float left = uDamage.z * smoothstep(.45, 1., sx) * (1. - abs(fx) * .45), right = uDamage.w * smoothstep(.45, 1., -sx) * (1. - abs(fx) * .45);',
    '  lp.z -= front * (.10 + .30 * nz); lp.y -= front * .05 * nz;',
    '  lp.z += rear * (.10 + .26 * nz); lp.y -= rear * .04 * nz;',
    '  lp.x -= left * (.05 + .16 * nz); lp.x += right * (.05 + .16 * nz);',
    '#endif',
    '  vec4 p = vec4(lp, 1.);',
    '  vec3 w = vec3(dot(aM0, p), dot(aM1, p), dot(aM2, p));',
    '#ifdef SWAY',
    '  float sw = clamp(lp.y * .09, 0., 1.); sw *= sw;',
    '  w.x += sin(uTime * 1.3 + w.x * .21 + w.z * .17) * .16 * sw * (.6 + uWind.x * .5);',
    '  w.z += cos(uTime * 1.1 + w.z * .19) * .10 * sw * (.6 + uWind.x * .5);',
    '#endif',
    '  vec3 n = vec3(dot(aM0.xyz, aNrm), dot(aM1.xyz, aNrm), dot(aM2.xyz, aNrm));',
    '  vWorld = w; vN = n; vUV = aUV; vCol = aCol; vTint = aTint;',
    '  gl_Position = uViewProj * vec4(w, 1.);',
    '}'
  ].join('\n');

  /* ------------------------------------------------------------ lit fragment */
  S.litFS = [
    'precision highp float; precision highp sampler2DShadow;',
    'in vec3 vWorld; in vec3 vN; in vec2 vUV; in vec4 vCol; in vec4 vTint;',
    '#ifdef CAR',
    'in vec3 vLoc; uniform vec4 uArch; uniform vec2 uCarHalf;',
    '#endif',
    'out vec4 oColor;',
    NOISE, SKY_COMMON,
    'uniform sampler2D uTex0; uniform sampler2D uTex1; uniform sampler2D uTex2; uniform sampler2D uTex3;',
    'uniform sampler2DShadow uShadow0; uniform sampler2DShadow uShadow1; uniform sampler2DShadow uShadow2;',
    'uniform mat4 uLVP0; uniform mat4 uLVP1; uniform mat4 uLVP2; uniform int uNCasc; uniform vec3 uCascTexel;',
    'uniform vec3 uCam; uniform vec3 uSkyAmb; uniform float uAmb;',
    'uniform vec4 uBase; uniform float uRough; uniform float uMetal; uniform vec3 uEmis; uniform vec2 uTexScale; uniform float uNormStr;',
    'uniform float uClear; uniform float uFlake; uniform float uWet; uniform float uWetAffect; uniform float uAlphaCut; uniform float uSpec;',
    'uniform vec3 uFogCol; uniform float uFogDen; uniform float uFogHF; uniform float uFogBase; uniform float uFogSun;',
    'uniform int uNSpot; uniform vec4 uSpot[8]; uniform vec4 uSpotD[8]; uniform vec4 uSpotC[8];',
    'uniform float uSnow; uniform vec4 uTintMul; uniform float uClipY;',
    'uniform int uNAO; uniform vec4 uAO0[8]; uniform vec4 uAO1[8]; uniform vec4 uAO2[8];',
    '#ifdef REFL',
    'uniform sampler2D uReflTex; uniform vec2 uViewport; uniform float uReflOn;',
    '#endif',
    'const float PI = 3.14159265;',
    'float D_GGX(float nh, float a){ float a2 = a * a; float d = nh * nh * (a2 - 1.) + 1.; return a2 / (PI * d * d + 1e-5); }',
    'float V_Smith(float nv, float nl, float a){ float g1 = nl * (nv * (1. - a) + a); float g2 = nv * (nl * (1. - a) + a); return .5 / (g1 + g2 + 1e-4); }',
    'vec3 F_Schlick(vec3 f0, float vh){ return f0 + (1. - f0) * pow(1. - vh, 5.); }',
    'vec3 envBRDF(vec3 f0, float r, float nv){',
    '  const vec4 c0 = vec4(-1., -.0275, -.572, .022); const vec4 c1 = vec4(1., .0425, 1.04, -.04);',
    '  vec4 rr = r * c0 + c1; float a004 = min(rr.x * rr.x, exp2(-9.28 * nv)) * rr.x + rr.y;',
    '  vec2 AB = vec2(-1.04, 1.04) * a004 + rr.zw; return f0 * AB.x + AB.y; }',
    'vec3 perturb(vec3 N, vec3 p, vec2 uv, vec2 nxy, float k){',
    '  vec3 dp1 = dFdx(p), dp2 = dFdy(p); vec2 du1 = dFdx(uv), du2 = dFdy(uv);',
    '  vec3 d2p = cross(dp2, N), d1p = cross(N, dp1);',
    '  vec3 T = d2p * du1.x + d1p * du2.x; vec3 B = d2p * du1.y + d1p * du2.y;',
    '  float im = inversesqrt(max(max(dot(T, T), dot(B, B)), 1e-12));',
    '  vec2 q = nxy * k; vec3 nt = vec3(q, sqrt(max(0., 1. - dot(q, q))));',
    '  return normalize(T * im * nt.x + B * im * nt.y + N * nt.z); }',
    'float shadowLookup(sampler2DShadow s, mat4 vp, vec3 wp, vec3 n, float texel, float bias){',
    '  vec3 pos = wp + n * texel * 2.2;',
    '  vec4 lp = vp * vec4(pos, 1.); vec3 c = lp.xyz * .5 + .5;',
    '  if (c.x < .02 || c.x > .98 || c.y < .02 || c.y > .98 || c.z > 1.) return -1.;',
    '  c.z -= bias;',
    '  vec2 t = vec2(texel * 0.0); float sum = 0.;',
    '  const float k = 1.;',
    '  vec2 px = vec2(1.) / vec2(textureSize(s, 0));',
    '  for (int x = -1; x <= 1; x++) for (int y = -1; y <= 1; y++) sum += texture(s, vec3(c.xy + vec2(float(x), float(y)) * px * 1.15, c.z));',
    '  return sum / 9.; }',
    'float sunShadow(vec3 wp, vec3 n, float nl){',
    '  float bias = .0006 + .0016 * (1. - nl);',
    '  float s = shadowLookup(uShadow0, uLVP0, wp, n, uCascTexel.x, bias);',
    '  if (s >= 0.) return s;',
    '  if (uNCasc > 1) { s = shadowLookup(uShadow1, uLVP1, wp, n, uCascTexel.y, bias * 1.4); if (s >= 0.) return s; }',
    '  if (uNCasc > 2) { s = shadowLookup(uShadow2, uLVP2, wp, n, uCascTexel.z, bias * 1.8); if (s >= 0.) return s; }',
    '  return 1.; }',
    'void main(){',
    '  if (vWorld.y < uClipY) discard;',
    '  vec2 uv = vUV * uTexScale;',
    '#ifdef CAR',
    '  if (uArch.w > 0. && abs(vLoc.x) > uCarHalf.y * .62) { float dyA = vLoc.y - uArch.z; float dA = min(dyA > 0. ? length(vec2(vLoc.z - uArch.x, dyA)) : abs(vLoc.z - uArch.x), dyA > 0. ? length(vec2(vLoc.z - uArch.y, dyA)) : abs(vLoc.z - uArch.y)); if (dA < uArch.w) discard; }',
    '#endif',
    '  vec4 t0 = texture(uTex0, uv); vec4 t1 = texture(uTex1, uv);',
    '#ifdef TERRAIN',
    '  { vec2 uv2 = uv * .37 + vec2(.31, .17); vec4 r0 = texture(uTex2, uv2); vec4 r1 = texture(uTex3, uv2);',
    '    float sp = vCol.a; t0 = mix(t0, r0, sp); t1 = mix(t1, r1, sp); }',
    '#endif',
    '  vec3 albedo = t0.rgb * vCol.rgb * vTint.rgb * uBase.rgb * uTintMul.rgb;',
    '  float alpha = uBase.a * vTint.a;',
    '#ifdef ALPHATEST',
    '  if (t0.a * alpha < uAlphaCut) discard;',
    '#endif',
    '#ifdef TERRAIN',
    '  float ao = 1.;',
    '#else',
    '  float ao = vCol.a;',
    '#endif',
    '  // ---- analytic contact occlusion under / around every car (rounded-box footprint + 4 tyre contact patches) ----',
    '  float carOcc = 0.;',
    '#ifndef CAR',
    '  for (int i = 0; i < 8; i++) { if (i >= uNAO) break;',
    '    vec4 a0 = uAO0[i], a1 = uAO1[i], a2 = uAO2[i];',
    '    float hh = vWorld.y - a1.z; if (hh < -.4 || hh > .9) continue;',
    '    vec2 dd0 = vWorld.xz - a0.xy; float lz = dd0.x * a0.z + dd0.y * a0.w; float lx = dd0.x * a0.w - dd0.y * a0.z;',
    '    vec2 q = abs(vec2(lx, lz)) - (a1.xy - .45); float sdb = length(max(q, 0.)) + min(max(q.x, q.y), 0.) - .45;',
    '    float hv = 1. - smoothstep(.1, .8, hh);',
    '    float body = (1. - smoothstep(-.1, .9, sdb)); body = body * body * hv;',
    '    float wc = 0.;',
    '    for (int w = 0; w < 4; w++) { vec2 wp = vec2((w & 1) == 0 ? a2.x : -a2.x, w < 2 ? a2.y : a2.z); vec2 dw = (vec2(lx, lz) - wp) / vec2(a2.w * .62, a2.w * 1.3); wc = max(wc, 1. - smoothstep(.45, 1.8, length(dw))); }',
    '    carOcc = max(carOcc, max(body * .72, wc * .9 * hv));',
    '  }',
    '  ao *= 1. - .85 * carOcc;',
    '#endif',
    '  vec3 Ng = normalize(vN); if (!gl_FrontFacing) Ng = -Ng;',
    '  vec3 V = normalize(uCam - vWorld); float dist = length(uCam - vWorld);',
    '  vec2 nxy = t1.rg * 2. - 1.;',
    '  vec3 N = perturb(Ng, vWorld, uv, nxy, uNormStr);',
    '  float rough = clamp(t1.b * uRough, .04, 1.);',
    '  float metal = uMetal;',
    '  vec3 emis = uEmis * (1. + t1.a * 6.) * step(.001, uEmis.x + uEmis.y + uEmis.z);',
    '#ifdef EMISMASK',
    '  emis = uEmis * t1.a;',
    '#endif',
    '#ifdef CAR',
    '  if (uFlake > 0.) { vec3 fl = floor(vWorld * 260.); vec3 fn = vec3(hash13(fl), hash13(fl + 7.1), hash13(fl + 13.7)) - .5; N = normalize(N + fn * uFlake * .35); }',
    '#endif',
    '  // ---- wet / snow surface modification (ground materials) ----',
    '  float wetMask = 0.;',
    '  if (uWetAffect > 0.) {',
    '    float pud = fbm3(vWorld.xz * .09 + 3.1) * .7 + fbm3(vWorld.xz * .55) * .3;',
    '    wetMask = clamp(uWet * (.55 + 1.5 * smoothstep(.42, .62, pud) ), 0., 1.) * uWetAffect;',
    '    albedo *= mix(1., .55, wetMask); rough = mix(rough, .06, wetMask * .92);',
    '    N = normalize(mix(N, Ng, wetMask * .6));',
    '  }',
    '  if (uSnow > 0. && uWetAffect > 0.) { float sn = clamp(uSnow * (.8 + .4 * fbm3(vWorld.xz * .3)), 0., 1.) * smoothstep(.55, .9, Ng.y);',
    '    albedo = mix(albedo, vec3(.82, .86, .92), sn); rough = mix(rough, .75, sn); metal *= 1. - sn; }',
    '  float nv = max(dot(N, V), 1e-3);',
    '  vec3 f0 = mix(vec3(.04) * uSpec, albedo, metal);',
    '  vec3 diffCol = albedo * (1. - metal);',
    '  float a = rough * rough;',
    '  // ---- sun ----',
    '  float nlg = max(dot(Ng, uSunDir), 0.);',
    '  float nl = max(dot(N, uSunDir), 0.);',
    '  float sh = 1.;',
    '  if (uNCasc > 0 && nlg > 0.) sh = sunShadow(vWorld, Ng, nlg);',
    '  sh = min(sh, 1. - .8 * carOcc);',
    '  vec3 H = normalize(V + uSunDir);',
    '  float nh = max(dot(N, H), 0.), vh = max(dot(V, H), 0.);',
    '  vec3 F = F_Schlick(f0, vh);',
    '  vec3 spec = D_GGX(nh, a) * V_Smith(nv, nl, a) * F;',
    '  vec3 col = (diffCol * (1. - F) / PI + spec) * uSunCol * nl * sh;',
    '  // ---- clearcoat (car paint) ----',
    '#ifdef CAR',
    '  if (uClear > 0.) {',
    '    float ccr = .05; float aa = ccr * ccr; float Fc = .04 + .96 * pow(1. - vh, 5.);',
    '    col += D_GGX(nh, aa) * V_Smith(nv, nl, aa) * Fc * uSunCol * nl * sh * uClear;',
    '  }',
    '#endif',
    '  // ---- ambient / IBL from the analytic sky ----',
    '  vec3 R = reflect(-V, N);',
    '  float up = N.y * .5 + .5;',
    '  vec3 amb = mix(uGround, uSkyAmb, up) * uAmb;',
    '  col += diffCol * amb * ao;',
    '  vec3 Rsky = R; if (Rsky.y < 0.) Rsky.y = abs(Rsky.y) * .25;',
    '  vec3 envSky = mix(skyBase(normalize(Rsky), 1.), uSkyAmb * 1.1, rough * rough * .85);',
    '  float horizonOcc = clamp(1. + 1.4 * dot(R, Ng), 0., 1.);',
    '  vec3 spAmb = envBRDF(f0, rough, nv);',
    '  vec3 envCol = envSky * spAmb * mix(.35, 1., sh) * ao * horizonOcc;',
    '#ifdef REFL',
    '  if (uReflOn > 0. && wetMask > .02) {',
    '    vec2 suv = gl_FragCoord.xy / uViewport; suv.x += N.x * .02; suv.y += (N.z * .012);',
    '    vec3 rc = texture(uReflTex, vec2(suv.x, suv.y)).rgb;',
    '    float fr = F_Schlick(vec3(.02), nv).x * 1.0 + .06;',
    '    envCol = mix(envCol, rc * (fr * 4. + .15), clamp(wetMask * .85, 0., 1.));',
    '  }',
    '#endif',
    '#ifdef CAR',
    '  if (uClear > 0.) { float Fc2 = .04 + .96 * pow(1. - nv, 5.); envCol += envSky * Fc2 * uClear * ao * .55; }',
    '#endif',
    '  col += envCol;',
    '  // ---- spot lights (headlights) ----',
    '  for (int i = 0; i < 8; i++) {',
    '    if (i >= uNSpot) break;',
    '    vec3 Lv = uSpot[i].xyz - vWorld; float d = length(Lv); if (d > uSpot[i].w) continue; Lv /= d;',
    '    float cone = smoothstep(uSpotD[i].w, uSpotC[i].w, dot(-Lv, uSpotD[i].xyz));',
    '    float att = pow(clamp(1. - d / uSpot[i].w, 0., 1.), 2.) / (1. + d * d * .0025);',
    '    vec3 Ns = normalize(mix(N, Ng, .65));',
    '    float snl = max(dot(Ns, Lv), 0.);',
    '    vec3 Hs = normalize(V + Lv); float snh = max(dot(Ns, Hs), 0.);',
    '    vec3 sp = D_GGX(snh, a) * V_Smith(nv, snl, a) * F_Schlick(f0, max(dot(V, Hs), 0.));',
    '    col += (diffCol / PI + sp) * uSpotC[i].rgb * snl * cone * att * 60.;',
    '  }',
    '  col += emis;',
    '  // ---- fog ----',
    '  vec3 vv = vWorld - uCam; float dd = length(vv); vec3 dir = vv / max(dd, 1e-3);',
    '  float avgH = (uCam.y + vWorld.y) * .5;',
    '  float den = uFogDen * exp(-uFogHF * max(avgH - uFogBase, 0.));',
    '  float fa = 1. - exp(-den * dd);',
    '  vec3 fogC = uFogCol + uSunCol * pow(max(dot(dir, uSunDir), 0.), 5.) * uFogSun;',
    '  col = mix(col, fogC, fa);',
    '#ifdef GLASS',
    '  float Fg = .04 + .96 * pow(1. - nv, 4.);',
    '  alpha = clamp(alpha + Fg * .8, 0., 1.);',
    '#endif',
    '  oColor = vec4(col, alpha);',
    '}'
  ].join('\n');

  /* ------------------------------------------------------------ shadow pass */
  S.shadowVS = [
    'precision highp float;',
    'in vec3 aPos; in vec2 aUV; in vec4 aM0; in vec4 aM1; in vec4 aM2; in vec4 aTint; in vec4 aCol;',
    'uniform mat4 uLVP; out vec2 vUV;',
    'void main(){ vec4 p = vec4(aPos, 1.); vec3 w = vec3(dot(aM0, p), dot(aM1, p), dot(aM2, p)); vUV = aUV; gl_Position = uLVP * vec4(w, 1.); }'
  ].join('\n');
  S.shadowFS = [
    'precision highp float; in vec2 vUV; out vec4 o; uniform sampler2D uTex0; uniform vec2 uTexScale; uniform float uAlphaCut;',
    'void main(){',
    '#ifdef ALPHATEST',
    '  if (texture(uTex0, vUV * uTexScale).a < uAlphaCut) discard;',
    '#endif',
    '  o = vec4(1.); }'
  ].join('\n');

  /* ------------------------------------------------------------ sky */
  S.skyVS = [
    'precision highp float; out vec2 vP;',
    'void main(){ vec2 p = vec2((gl_VertexID << 1) & 2, gl_VertexID & 2); vP = p * 2. - 1.; gl_Position = vec4(vP, 1., 1.); }'
  ].join('\n');
  S.skyFS = [
    'precision highp float; in vec2 vP; out vec4 oColor;',
    NOISE, SKY_COMMON,
    'uniform mat4 uInvVP; uniform vec3 uCam; uniform vec2 uWind; uniform vec3 uCloudCol;',
    'float stars(vec3 d){ vec2 p = d.xz / (abs(d.y) + .6) * 90.; vec2 i = floor(p), f = fract(p) - .5;',
    '  float h = hash12(i); float s = smoothstep(.97, 1., h); float r = length(f + (vec2(hash12(i + 3.1), hash12(i + 8.7)) - .5) * .5);',
    '  return s * smoothstep(.12, .0, r) * (.5 + .5 * hash12(i + 1.7)) * 2.5; }',
    'void main(){',
    '  vec4 w = uInvVP * vec4(vP, 1., 1.); vec3 d = normalize(w.xyz / w.w - uCam);',
    '  vec3 col = skyBase(d, 1.);',
    '  if (d.y > 0.) {',
    '    vec2 cp = d.xz / (d.y + .14) * 1.1 + uTime * uWind * .012;',
    '    float n = fbm(cp * .8); float n2 = fbm(cp * 2.3 + 5.);',
    '    float cov = uCloud; float c = smoothstep(1. - cov - .02, 1. - cov + .30, n * .8 + n2 * .35);',
    '    c *= smoothstep(0., .22, d.y);',
    '    float lit = clamp(dot(vec3(0., 1., 0.), uSunDir) * .5 + .6, .15, 1.);',
    '    float shade = mix(.55, 1., smoothstep(.2, .8, 1. - n2));',
    '    vec3 cc = uCloudCol * (shade * lit + pow(max(dot(d, uSunDir), 0.), 12.) * .5 * (1. - c * .5));',
    '    col = mix(col, cc, c * (.92 - uNight * .2));',
    '    col += vec3(.75, .85, 1.) * stars(d) * uNight * (1. - c);',
    '    float md = max(dot(d, uMoonDir), 0.);',
    '    col += vec3(.9, .95, 1.) * smoothstep(.9992, .9997, md) * 1.6 * uNight * (1. - c);',
    '  }',
    '  oColor = vec4(col, 1.);',
    '}'
  ].join('\n');

  /* ------------------------------------------------------------ particles (instanced billboards) */
  S.partVS = [
    'precision highp float;',
    'in vec4 aI0; in vec4 aI1; in vec4 aI2;',  /* pos.xyz,size | color rgba | rot, kind, soft, stretch */
    'uniform mat4 uViewProj; uniform vec3 uCamRight; uniform vec3 uCamUp; uniform vec3 uCam;',
    'out vec2 vUV; out vec4 vCol; out float vKind; out float vSoft;',
    'void main(){',
    '  vec2 q = vec2(float(gl_VertexID & 1), float((gl_VertexID >> 1) & 1)) * 2. - 1.;',
    '  vUV = q; vCol = aI1; vKind = aI2.y; vSoft = aI2.z;',
    '  float s = aI0.w; float rot = aI2.x;',
    '  float c = cos(rot), sn = sin(rot);',
    '  vec2 r = vec2(q.x * c - q.y * sn, q.x * sn + q.y * c);',
    '  vec3 right = uCamRight, up = uCamUp;',
    '  vec3 wp;',
    '  if (aI2.w > 0.) {',   /* velocity-stretched streak: aI2.x holds nothing, direction in aI0? use rot as dir encoded below */
    '    wp = aI0.xyz + (uCamRight * q.x * s) + (uCamUp * q.y * s * aI2.w);',
    '  } else wp = aI0.xyz + (right * r.x + up * r.y) * s;',
    '  gl_Position = uViewProj * vec4(wp, 1.);',
    '}'
  ].join('\n');
  S.partFS = [
    'precision highp float; in vec2 vUV; in vec4 vCol; in float vKind; in float vSoft; out vec4 oColor;',
    NOISE,
    'uniform float uExposureAdd;',
    'void main(){',
    '  float r2 = dot(vUV, vUV); if (r2 > 1.) discard;',
    '  float a;',
    '  if (vKind < .5) {',           /* smoke puff: soft noisy disc */
    '    float n = vnoise(vUV * 2.4 + vCol.rg * 31.); a = smoothstep(1., .15, sqrt(r2)) * (.65 + .6 * n); }',
    '  else if (vKind < 1.5) {',     /* spark / ember: bright core */
    '    a = pow(1. - sqrt(r2), 2.2); }',
    '  else if (vKind < 2.5) {',     /* rain streak (vertical) */
    '    float w = abs(vUV.x); a = smoothstep(.55, .0, w) * smoothstep(1., .55, abs(vUV.y)) * .9; }',
    '  else if (vKind < 3.5) {',     /* snow flake */
    '    a = smoothstep(1., .35, sqrt(r2)); }',
    '  else {',                       /* glow sprite (lights) */
    '    float d = sqrt(r2); a = pow(1. - d, 2.) * .8 + exp(-d * 5.) * .6; }',
    '  oColor = vec4(vCol.rgb, vCol.a * a);',
    '}'
  ].join('\n');

  /* ------------------------------------------------------------ decals / skidmarks / unlit-ish */
  S.decalFS = [
    'precision highp float;',
    'in vec3 vWorld; in vec3 vN; in vec2 vUV; in vec4 vCol; in vec4 vTint; out vec4 oColor;',
    NOISE,
    'uniform vec3 uCam; uniform vec3 uFogCol; uniform float uFogDen; uniform float uWet; uniform vec3 uSunCol; uniform vec3 uSkyAmb;',
    'void main(){',
    '  float n = vnoise(vWorld.xz * 9.) * .5 + vnoise(vWorld.xz * 31.) * .5;',
    '  float edge = smoothstep(0., .22, vUV.x) * smoothstep(1., .78, vUV.x);',
    '  float a = vCol.a * edge * (.55 + .5 * n) * mix(1., .55, uWet);',
    '  vec3 col = vec3(.012, .011, .010) * (uSkyAmb * .6 + .3);',
    '  float dd = length(vWorld - uCam); float fa = 1. - exp(-uFogDen * dd);',
    '  col = mix(col, uFogCol, fa);',
    '  oColor = vec4(col, a * (1. - fa * .6));',
    '}'
  ].join('\n');

  /* additive light-cone volumes / flat glow quads share this one */
  S.volFS = [
    'precision highp float;',
    'in vec3 vWorld; in vec3 vN; in vec2 vUV; in vec4 vCol; in vec4 vTint; out vec4 oColor;',
    'uniform vec3 uCam; uniform vec4 uBase;',
    'void main(){',
    '  vec3 V = normalize(uCam - vWorld); float f = pow(abs(dot(normalize(vN), V)), 1.5);',
    '  float along = 1. - vUV.y;',
    '  float a = f * along * along * uBase.a * vCol.a;',
    '  oColor = vec4(uBase.rgb * vCol.rgb, a);',
    '}'
  ].join('\n');

  /* ------------------------------------------------------------ post processing */
  var POST_VS = 'precision highp float; out vec2 vUV; void main(){ vec2 p = vec2((gl_VertexID << 1) & 2, gl_VertexID & 2); vUV = p; gl_Position = vec4(p * 2. - 1., 0., 1.); }';
  S.postVS = POST_VS;
  S.bloomDownFS = [
    'precision highp float; in vec2 vUV; out vec4 o; uniform sampler2D uTex; uniform vec2 uTexel; uniform float uFirst; uniform float uThresh;',
    'vec3 pre(vec3 c){ float l = max(max(c.r, c.g), c.b); float k = max(l - uThresh, 0.) / max(l, 1e-4); return c * k; }',
    'void main(){',
    '  vec2 t = uTexel;',
    '  vec3 a = texture(uTex, vUV + t * vec2(-2, 2)).rgb, b = texture(uTex, vUV + t * vec2(0, 2)).rgb, c = texture(uTex, vUV + t * vec2(2, 2)).rgb;',
    '  vec3 d = texture(uTex, vUV + t * vec2(-2, 0)).rgb, e = texture(uTex, vUV).rgb, f = texture(uTex, vUV + t * vec2(2, 0)).rgb;',
    '  vec3 g = texture(uTex, vUV + t * vec2(-2, -2)).rgb, h = texture(uTex, vUV + t * vec2(0, -2)).rgb, i = texture(uTex, vUV + t * vec2(2, -2)).rgb;',
    '  vec3 j = texture(uTex, vUV + t * vec2(-1, 1)).rgb, k = texture(uTex, vUV + t * vec2(1, 1)).rgb, l = texture(uTex, vUV + t * vec2(-1, -1)).rgb, m = texture(uTex, vUV + t * vec2(1, -1)).rgb;',
    '  if (uFirst > .5) { a = pre(a); b = pre(b); c = pre(c); d = pre(d); e = pre(e); f = pre(f); g = pre(g); h = pre(h); i = pre(i); j = pre(j); k = pre(k); l = pre(l); m = pre(m); }',
    '  vec3 r = e * .125 + (a + c + g + i) * .03125 + (b + d + f + h) * .0625 + (j + k + l + m) * .125;',
    '  o = vec4(min(r, vec3(60.)), 1.); }'
  ].join('\n');
  S.bloomUpFS = [
    'precision highp float; in vec2 vUV; out vec4 o; uniform sampler2D uTex; uniform vec2 uTexel; uniform float uRadius;',
    'void main(){',
    '  vec2 t = uTexel * uRadius;',
    '  vec3 s = texture(uTex, vUV).rgb * 4.;',
    '  s += texture(uTex, vUV + vec2(-t.x, 0)).rgb * 2. + texture(uTex, vUV + vec2(t.x, 0)).rgb * 2. + texture(uTex, vUV + vec2(0, -t.y)).rgb * 2. + texture(uTex, vUV + vec2(0, t.y)).rgb * 2.;',
    '  s += texture(uTex, vUV + vec2(-t.x, -t.y)).rgb + texture(uTex, vUV + vec2(t.x, -t.y)).rgb + texture(uTex, vUV + vec2(-t.x, t.y)).rgb + texture(uTex, vUV + vec2(t.x, t.y)).rgb;',
    '  o = vec4(s / 16., 1.); }'
  ].join('\n');
  S.compositeFS = [
    'precision highp float; in vec2 vUV; out vec4 o;',
    'uniform sampler2D uScene; uniform sampler2D uBloom; uniform sampler2D uDepth;',
    'uniform float uExposure; uniform float uBloomAmt; uniform float uVig; uniform float uGrain; uniform float uTime;',
    'uniform float uMotion; uniform vec2 uMotionCenter; uniform float uDof; uniform float uFocus; uniform vec2 uNearFar; uniform vec2 uTexel;',
    'uniform float uSat; uniform vec3 uTint; uniform float uContrast; uniform float uRainLens; uniform float uFade; uniform float uAberr;',
    'float linD(float d){ float z = d * 2. - 1.; return 2. * uNearFar.x * uNearFar.y / (uNearFar.y + uNearFar.x - z * (uNearFar.y - uNearFar.x)); }',
    'vec3 aces(vec3 x){ const float a = 2.51, b = .03, c = 2.43, d = .59, e = .14; return clamp((x * (a * x + b)) / (x * (c * x + d) + e), 0., 1.); }',
    'float h12(vec2 p){ vec3 p3 = fract(vec3(p.xyx) * .1031); p3 += dot(p3, p3.yzx + 33.33); return fract((p3.x + p3.y) * p3.z); }',
    'void main(){',
    '  vec2 uv = vUV;',
    '  vec2 dc = uv - uMotionCenter; float rr = length(dc);',
    '  vec3 col;',
    '  vec2 ab = dc * uAberr * (rr * rr);',
    '  if (uMotion > 0.001) {',
    '    vec3 acc = vec3(0.); const int N = 9;',
    '    for (int i = 0; i < N; i++) { float k = float(i) / float(N - 1); vec2 q = uv - dc * uMotion * k * smoothstep(.12, .75, rr * 1.5); acc += texture(uScene, q).rgb; }',
    '    col = acc / float(N);',
    '  } else {',
    '    col = vec3(texture(uScene, uv - ab).r, texture(uScene, uv).g, texture(uScene, uv + ab).b);',
    '  }',
    '  if (uDof > .01) {',
    '    float d = linD(texture(uDepth, uv).r);',
    '    float coc = clamp((d - uFocus) / (uFocus * 3.2 + 4.), 0., 1.) * uDof;',
    '    if (coc > .02) {',
    '      vec3 acc = col; float wsum = 1.;',
    '      for (int i = 0; i < 12; i++) { float a = float(i) * 2.39996; float r = sqrt(float(i) + .5) / 3.5;',
    '        vec2 off = vec2(cos(a), sin(a)) * r * coc * 7. * uTexel; vec3 s = texture(uScene, uv + off).rgb;',
    '        acc += s; wsum += 1.; }',
    '      col = mix(col, acc / wsum, smoothstep(.02, .3, coc));',
    '    }',
    '  }',
    '  col += texture(uBloom, uv).rgb * uBloomAmt;',
    '  col *= uExposure;',
    '  col = aces(col);',
    '  col = pow(col, vec3(1. / 2.2));',
    '  float l = dot(col, vec3(.2126, .7152, .0722));',
    '  col = mix(vec3(l), col, uSat) * uTint;',
    '  col = (col - .5) * uContrast + .5;',
    '  float vg = smoothstep(1.15, .35, rr * 1.35); col *= mix(1., vg, uVig);',
    '  col += (h12(gl_FragCoord.xy + fract(uTime) * 91.) - .5) * uGrain;',
    '  col *= uFade;',
    '  o = vec4(max(col, 0.), 1.); }'
  ].join('\n');
  S.copyFS = 'precision highp float; in vec2 vUV; out vec4 o; uniform sampler2D uTex; void main(){ o = vec4(texture(uTex, vUV).rgb, 1.); }';

  JR.shaders = S;
  if (typeof module !== 'undefined' && module.exports) module.exports = JR;
})();
